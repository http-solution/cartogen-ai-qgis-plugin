# ---- link rewriting ----------------------------------------------------------------------------------------------------------------
class Linker:
    def __init__(self, pages, out):
        self.pages = pages                                   # slug -> Page
        self.by_src = {p.spec.get("path"): p for p in pages.values() if p.spec.get("path")}
        self.out = out
        self.errors = []
        self.warnings = []
        self.assets = {}

    @staticmethod
    def rel(from_url, to_url):
        d = posixpath.dirname(from_url) or "."
        return posixpath.relpath(to_url, d)

    def asset(self, repo_path, from_page):
        dest = "assets/repo/" + repo_path
        if repo_path not in self.assets:
            src = REPO / repo_path
            if not src.is_file():
                self.errors.append(f"{from_page.slug}: image {repo_path} not found")
                return None
            self.assets[repo_path] = dest
            (self.out / dest).parent.mkdir(parents=True, exist_ok=True)
            shutil.copy2(src, self.out / dest)
        return self.rel(from_page.url, dest)

    def github(self, repo_path):
        full = REPO / repo_path
        kind = "tree" if full.is_dir() else "blob"
        return f"{GITHUB}/{kind}/{BRANCH}/{repo_path}".rstrip("/")

    def resolve(self, href, page, attr):
        if re.match(r"^(https?:|mailto:|data:|javascript:|tel:)", href) or href.startswith("#"):
            return href
        frag = ""
        target = href
        if "#" in href:
            target, frag = href.split("#", 1)
            frag = "#" + frag
        if target.startswith("@"):
            slug = target[1:]
            if slug not in self.pages:
                self.errors.append(f"{page.slug}: link to unknown page {href}")
                return href
            return self.rel(page.url, self.pages[slug].url) + frag
        if target.startswith(("repo:", "asset:")):
            repo_path = target.split(":", 1)[1]
            return self.repo_target(repo_path, frag, page, attr)
        if page.mirror:
            base = posixpath.dirname(page.spec.get("path", ""))
            repo_path = posixpath.normpath(posixpath.join(base, target)) if target else page.spec.get("path", "")
            return self.repo_target(repo_path, frag, page, attr, lenient=True)
        self.errors.append(f"{page.slug}: relative link {href!r} must use @slug or repo:path")
        return href

    def repo_target(self, repo_path, frag, page, attr, lenient=False):
        if repo_path in self.by_src:
            return self.rel(page.url, self.by_src[repo_path].url) + frag
        if repo_path == "docs/TOOLS_REFERENCE.md":
            return self.rel(page.url, self.pages["tools/index"].url) + frag
        full = REPO / repo_path
        if repo_path.lower().endswith(IMAGE_EXTS) and (attr == "src" or full.is_file()):
            a = self.asset(repo_path, page)
            return a if a else repo_path
        if not full.exists():
            (self.warnings if lenient else self.errors).append(f"{page.slug}: {repo_path} does not exist in the repository")
            return self.github(repo_path) + frag
        return self.github(repo_path) + frag

    def rewrite(self, html_text, page):
        def sub(m):
            attr, quote, val = m.group(1), m.group(2), m.group(3)
            new = self.resolve(html.unescape(val), page, attr)
            return f'{attr}={quote}{html.escape(new, quote=False)}{quote}'
        return re.sub(r'\b(href|src)=(["\'])(.*?)\2', sub, html_text)


# ---- build --------------------------------------------------------------------------------------------------------------------------
def sections_first(sections):
    return sections[0][0]


def nav_html(sections, current, base_rel):
    out = []
    for title, pages in sections:
        is_open = any(p.slug == current.slug for p in pages) or (current.slug == "index" and title == sections_first(sections))
        out.append(f"<details{' open' if is_open else ''}><summary>{html.escape(title)}</summary><ul>")
        for p in pages:
            aria = ' aria-current="page"' if p.slug == current.slug else ""
            out.append(f'<li><a href="{Linker.rel(current.url, p.url)}"{aria}>{html.escape(p.title)}</a></li>')
        out.append("</ul></details>")
    return "".join(out)


def toc_html(toc):
    items = [(lvl, name, id_) for lvl, name, id_ in toc if lvl in (2, 3)]
    if len(items) < 3:
        return ""
    lis = "".join(f'<li class="l{lvl}"><a href="#{id_}">{html.escape(re.sub(r"<[^>]+>", "", name))}</a></li>' for lvl, name, id_ in items[:60])
    return f'<aside class="toc" aria-label="On this page"><b>On this page</b><ul>{lis}</ul></aside>'


def strip_tags(s):
    s = re.sub(r"<(script|style)[^>]*>.*?</\1>", " ", s, flags=re.S)
    s = re.sub(r"<[^>]+>", " ", s)
    return " ".join(html.unescape(s).split())


def build(out_dir, facts):
    if out_dir.exists():
        shutil.rmtree(out_dir)
    out_dir.mkdir(parents=True)
    (out_dir / "assets").mkdir()
    shutil.copy2(SITE / "theme" / "style.css", out_dir / "assets" / "style.css")
    shutil.copy2(SITE / "theme" / "site.js", out_dir / "assets" / "site.js")
    shutil.copy2(REPO / "branding" / "cartogen-mark.svg", out_dir / "assets" / "mark.svg")
    (out_dir / ".nojekyll").write_text("")

    ctx = {"facts": facts, "toolref": split_tool_reference()}
    _head, cats = ctx["toolref"]
    named = [c for c in cats if not re.fullmatch(r"[a-z0-9_]+", c)]

    # expand the tool category pages into the nav
    nav = []
    for title, base_specs in NAV:
        specs = list(base_specs)
        if title == "Tools and data":
            extra = [{"slug": "tools/" + slugify(c), "title": c, "kind": "gen", "gen": "tool_category", "arg": c} for c in named]
            extra.append({"slug": "tools/more", "title": "More tools, by module", "kind": "gen", "gen": "tools_more"})
            specs = [specs[0], *extra, *specs[1:]]
        nav.append((title, specs))

    sections = []
    pages = OrderedDict()
    home = Page(HOME, "Home")
    pages[home.slug] = home
    for title, specs in nav:
        ps = []
        for spec in specs:
            page = Page(spec, title)
            if page.slug in pages:
                sys.exit(f"duplicate slug {page.slug}")
            pages[page.slug] = page
            ps.append(page)
        sections.append((title, ps))

    # 1. markdown source for every page
    sources = {}
    for page in pages.values():
        spec = page.spec
        if spec["kind"] == "content":
            meta, text = strip_front_matter((CONTENT / spec["file"]).read_text(encoding="utf-8"))
            page.description = meta.get("description", "")
            page.wide = page.wide or meta.get("wide") == "true"
            text = fill_facts(text, facts)
        elif spec["kind"] == "repo":
            text = prepare_mirrored((REPO / spec["path"]).read_text(encoding="utf-8"))
        else:
            gen = spec["gen"]
            if gen == "tool_category":
                text = gen_tool_category(ctx, spec["arg"])
                page.description = f"{spec['arg']} tools: arguments and behaviour."
            elif gen == "tools_more":
                text = gen_tools_more(ctx)
            else:
                text = GENERATORS[gen](ctx)
        sources[page.slug] = text

    # 2. render, 3. rewrite links, 4. write
    linker = Linker(pages, out_dir)
    ordered = [p for _, ps in sections for p in ps]
    index_entries = []
    flat = [home, *ordered]
    for page in flat:
        body, toc = render(sources[page.slug])
        body = linker.rewrite(body, page)
        page.toc = toc
        page.text = strip_tags(body)
        if not page.description:
            page.description = first_paragraph(sources[page.slug]) or page.title
        base_rel = Linker.rel(page.url, "index.html")
        base = "" if "/" not in page.url else "../" * page.url.count("/")
        crumbs = "" if page.slug == "index" else f'<div class="crumbs">{html.escape(page.section)} &rsaquo; {html.escape(page.title)}</div>'
        h1 = "" if (page.slug == "index" or body.lstrip().startswith("<h1")) else f"<h1>{html.escape(page.title)}</h1>"
        if page.mirror:
            h1 += (f'<p class="mirror">This page mirrors <a href="{linker.github(page.spec["path"])}"><code>{page.spec["path"]}</code></a> from the '
                   "repository and is rebuilt whenever that file changes. To correct it, edit the source file.</p>")
        elif page.generated:
            h1 += '<p class="mirror">This page is generated from the repository when the site is built.</p>'
        pos = flat.index(page)
        prev = flat[pos - 1] if pos > 0 else None
        nxt = flat[pos + 1] if pos + 1 < len(flat) else None
        pager = ""
        if page.slug != "index":
            pager = '<div class="pager">' + (f'<a class="prev" href="{Linker.rel(page.url, prev.url)}"><small>Previous</small>{html.escape(prev.title)}</a>' if prev and prev.slug != "index" else "<span></span>") + \
                    (f'<a class="next" href="{Linker.rel(page.url, nxt.url)}"><small>Next</small>{html.escape(nxt.title)}</a>' if nxt else "") + "</div>"
        tpl = (SITE / "template.html").read_text(encoding="utf-8")
        rendered = (tpl.replace("{{TITLE}}", html.escape(page.title if page.slug != "index" else "Cartogen AI documentation") + ("" if page.slug == "index" else " · Cartogen AI"))
                    .replace("{{DESCRIPTION}}", html.escape(page.description, quote=True))
                    .replace("{{BASE}}", base).replace("{{VERSION}}", html.escape(facts["version"])).replace("{{GITHUB}}", GITHUB)
                    .replace("{{NAV}}", nav_html(sections, page, base_rel))
                    .replace("{{WIDE}}", " wide" if page.wide else "").replace("{{CRUMBS}}", crumbs)
                    .replace("{{BODY}}", h1 + body).replace("{{PAGER}}", pager)
                    .replace("{{TOC}}", toc_html(toc)).replace("{{BUILD_DATE}}", facts["build_date"]))
        dest = out_dir / page.url
        dest.parent.mkdir(parents=True, exist_ok=True)
        dest.write_text(rendered, encoding="utf-8")
        heads = [[re.sub(r"<[^>]+>", "", n).replace("¶", "").strip(), id_] for lvl, n, id_ in toc if lvl in (2, 3)][:300]
        index_entries.append({"t": page.title, "u": page.url, "s": page.section, "h": heads, "x": page.text[:2500]})

    # 404 + search index
    nf = (SITE / "template.html").read_text(encoding="utf-8")
    nf = (nf.replace("{{TITLE}}", "Page not found · Cartogen AI").replace("{{DESCRIPTION}}", "Page not found").replace("{{BASE}}", "/cartogen-ai-qgis-plugin/")
          .replace("{{VERSION}}", facts["version"]).replace("{{GITHUB}}", GITHUB).replace("{{NAV}}", "").replace("{{WIDE}}", "").replace("{{CRUMBS}}", "")
          .replace("{{BODY}}", "<h1>Page not found</h1><p>That page does not exist. Try the search box, or go to the <a href=\"/cartogen-ai-qgis-plugin/index.html\">home page</a>.</p>")
          .replace("{{PAGER}}", "").replace("{{TOC}}", "").replace("{{BUILD_DATE}}", facts["build_date"]))
    (out_dir / "404.html").write_text(nf, encoding="utf-8")
    (out_dir / "search-index.js").write_text("window.SEARCH_INDEX=" + json.dumps(index_entries, ensure_ascii=False, separators=(",", ":")) + ";", encoding="utf-8")
    return pages, linker


def check_links(out_dir, pages, linker):
    """Every internal href/src must exist, and every #fragment must be an id on its target page. Mirrored repository documents get a warning
    for a missing fragment (their authors link in GitHub's slug style); authored and generated pages get an error."""
    ids = {}
    for p in out_dir.rglob("*.html"):
        ids[p.relative_to(out_dir).as_posix()] = set(re.findall(r'\bid="([^"]+)"', p.read_text(encoding="utf-8")))
    errors = list(linker.errors)
    warnings = list(linker.warnings)
    for page in pages.values():
        src = (out_dir / page.url).read_text(encoding="utf-8")
        body = src.split('<main id="content">', 1)[1].split("</main>", 1)[0]
        for _attr, raw in re.findall(r'\b(href|src)="([^"]+)"', body):
            val = html.unescape(raw)
            if re.match(r"^(https?:|mailto:|data:|javascript:|tel:)", val):
                continue
            target, _, frag = val.partition("#")
            if target:
                dest = posixpath.normpath(posixpath.join(posixpath.dirname(page.url), target))
                if not (out_dir / dest).exists():
                    errors.append(f"{page.slug}: {val} -> missing file {dest}")
                    continue
            else:
                dest = page.url
            if frag and dest.endswith(".html") and frag not in ids.get(dest, set()):
                msg = f"{page.slug}: {val} -> no #{frag} on {dest}"
                (warnings if page.mirror else errors).append(msg)
    return errors, warnings


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default=str(SITE / "_site"))
    ap.add_argument("--check", action="store_true", help="exit 1 on broken internal links or anchors")
    args = ap.parse_args()
    facts = collect_facts()
    out = Path(args.out).resolve()
    pages, linker = build(out, facts)
    errors, warnings = check_links(out, pages, linker)
    print(f"built {len(pages)} pages into {out} ({facts['version']}, {facts['tools']} tools, {facts['tasks']} tasks)")
    for w in warnings[:25]:
        print("warning:", w)
    if len(warnings) > 25:
        print(f"warning: ... and {len(warnings) - 25} more")
    for e in errors:
        print("ERROR:", e)
    if errors:
        print(f"{len(errors)} link error(s)")
        if args.check:
            return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
