def doc_line(path):
    t = path.read_text(encoding="utf-8", errors="replace")
    m = re.search(r"^# (.+)$", t, re.M)
    title = m.group(1).strip() if m else path.stem.replace("_", " ")
    return (title, path.name, first_paragraph(t.split("\n", 1)[1] if "\n" in t else t, 150))


