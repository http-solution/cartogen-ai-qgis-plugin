def split_tool_reference():
    """docs/TOOLS_REFERENCE.md -> intro text and an ordered {category: markdown} map. Categories are the capitalised headings; the
    snake_case ones (a module with no category yet) are gathered on one page by the caller."""
    text = read("docs/TOOLS_REFERENCE.md")
    head, *parts = re.split(r"^## ", text, flags=re.M)
    cats = OrderedDict()
    for part in parts:
        name, _, rest = part.partition("\n")
        cats[name.strip()] = rest.strip("\n")
    return head, cats


def slugify(name):
    return re.sub(r"[^a-z0-9]+", "-", name.lower()).strip("-")


def heading_id(name, flag):
    """The id Python-Markdown's toc gives the heading `### `name` _(flag)_` (its slugify of the heading's text)."""
    from markdown.extensions.toc import slugify
    return slugify(name + (f" ({flag})" if flag else ""), "-")


def tool_entries(body):
    """[(tool name, flag, first sentence of its description, heading id)] from one category's markdown."""
    out = []
    for m in re.finditer(r"^### `([^`]+)`([^\n]*)\n\n([^\n]+)", body, flags=re.M):
        flag = m.group(2).strip(" _()")
        first = re.split(r"(?<=[.!?])\s", " ".join(m.group(3).split()), maxsplit=1)[0]
        out.append((m.group(1), flag, first[:200], heading_id(m.group(1), flag)))
    return out


def gen_tools_index(ctx):
    _head, cats = ctx["toolref"]
    named = [c for c in cats if not re.fullmatch(r"[a-z0-9_]+", c)]
    rows = []
    allrows = []
    for c in named:
        ent = tool_entries(cats[c])
        rows.append(f"| [{c}](@tools/{slugify(c)}) | {len(ent)} | " + ", ".join(f"`{n}`" for n, _, _, _ in ent[:4]) + (" …" if len(ent) > 4 else "") + " |")
        for n, flag, d, hid in ent:
            allrows.append((n, c, flag, d, hid))
    more = [c for c in cats if re.fullmatch(r"[a-z0-9_]+", c)]
    more_ent = []
    for c in more:
        for n, flag, d, hid in tool_entries(cats[c]):
            more_ent.append((n, c, flag, d, hid))
    rows.append(f"| [More tools, by module](@tools/more) | {len(more_ent)} | " + ", ".join(f"`{n}`" for n, _, _, _, _ in more_ent[:4]) + " … |")
    allrows += more_ent
    total = len(allrows)
    body = [
        (f"The assistant can call **{ctx['facts']['tools']} tools**. This reference is generated from the live tool registry "
         "(`docs/generate_tools_reference.py`), so it matches the code. Each tool lists its arguments, which are required, and what they mean."),
        "",
        ("Flags you will see: **network-only** tools do HTTP or file work off the main thread; **two-phase** tools fetch on a worker thread and then "
         "build the layer on the main thread. See [Tools and routing](@architecture/tools) and [Threads, tasks and Stop](@architecture/threading)."),
        "",
        "## Categories", "",
        "| Category | Tools | Examples |", "|---|---|---|", *rows, "",
        f"## All tools, A to Z ({total})", "",
        "| Tool | Category | What it does |", "|---|---|---|",
    ]
    for n, c, flag, d, hid in sorted(allrows):
        target = "more" if c in more else slugify(c)
        desc = d.replace("|", "\\|")
        body.append(f"| [`{n}`](@tools/{target}#{hid}) | {c if c in named else c.replace('_', ' ')} | {desc}" + (f" _({flag})_" if flag else "") + " |")
    ctx["tool_total"] = total
    return "\n".join(body)


