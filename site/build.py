def read(path):
    return (REPO / path).read_text(encoding="utf-8")


def collect_facts():
    meta = read("metadata.txt")
    version = re.search(r"^version=(\S+)", meta, re.M).group(1)
    ref = read("docs/TOOLS_REFERENCE.md")
    tools = int(re.search(r"\((\d+) tools\)", ref).group(1))
