"""Generates docs/SNAPSHOTS.md: every dated or per-release document in docs/, listed once as a frozen snapshot.

Why an index and not a move: PLAN-040 stage 6 first proposed moving these into docs/archive/. Measured 2026-10-28, 71 of the 74 are
named by other files (QGIS_PRODUCTION_ARCHITECTURE_REVIEW_2026-09-04.md by 72), including frozen docs that must not be edited, so a
move would break links nobody may fix. The index gives the same "which docs are history" answer with every path unchanged.

    python tools/docs_index.py          # rewrite docs/SNAPSHOTS.md
    python tools/docs_index.py --check  # exit 1 if it is out of date (tests/test_docs_index.py does this)
"""
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DOCS = os.path.join(ROOT, "docs")
OUT = os.path.join(DOCS, "SNAPSHOTS.md")
# Dated (2026-10-04), per-release (rc15, RC22) or one-off run sheets. Living docs never match.
_SNAPSHOT = re.compile(r"\d{4}-\d{2}-\d{2}|_rc\d+|^RC\d+|^PR\d+|ACCEPTANCE_RUN_SHEET", re.IGNORECASE)
# Dated names that are nevertheless living (the master list is updated in place; the runbook doc is current guidance).
_LIVING = {"MASTER_TASK_LIST_2026-10-27.md"}


def snapshot_names():
    return [n for n in sorted(os.listdir(DOCS)) if n.endswith(".md") and n not in _LIVING and _SNAPSHOT.search(n)]


def _title(name):
    with open(os.path.join(DOCS, name), encoding="utf-8") as fh:
        for line in fh:
            if line.startswith("#"):
                return line.lstrip("#").strip().replace("|", "/")[:110]
    return name


def render():
    rows = [f"| [{n}]({n}) | {_title(n)} |" for n in snapshot_names()]
    return (
        "# Frozen snapshots in docs/\n\n"
        "Generated by `python tools/docs_index.py`; do not edit by hand. Each document below is accurate to the date or release in its name and is\n"
        "never rewritten (CLAUDE.md, \"frozen historical docs\"). Current state lives in `IMPLEMENTATION_TRACKER.md`, `BUG_TRACKER.md`,\n"
        "`MASTER_TASK_LIST_*`, `FEATURE_LEDGER.json` and `plans/`. They stay in place because other documents link to their paths.\n\n"
        f"{len(rows)} snapshots.\n\n| Document | Title |\n|---|---|\n" + "\n".join(rows) + "\n"
    )


def main(argv):
    text = render()
    if "--check" in argv:
        current = ""
        if os.path.exists(OUT):
            with open(OUT, encoding="utf-8") as fh:
                current = fh.read()
        if current != text:
            print("docs/SNAPSHOTS.md is out of date: run python tools/docs_index.py")
            return 1
        return 0
    with open(OUT, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(text)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
