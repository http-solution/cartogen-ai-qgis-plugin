"""Regenerates docs/PERSONA_CATALOGUE.md from the 15 persona files and the task register (PLAN-023 R1-6), so the catalogue can never say more than the files do.

    python docs/generate_persona_catalogue.py            # rewrite the catalogue
    python docs/generate_persona_catalogue.py --check    # exit 1 if the committed file is stale (tests/test_persona_catalogue.py does the same)

Needs no QGIS. The text is deterministic (no dates, no counts that change on their own), so a diff means a persona file, a task or a tool really changed."""
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, "src"))

from cartogen_ai.core import personas  # noqa: E402
from cartogen_ai.core.agent import task_register  # noqa: E402
from cartogen_ai.core.personas.panel import HEADINGS, _line  # noqa: E402

PATH = os.path.join(ROOT, "docs", "PERSONA_CATALOGUE.md")


def render():
    """The catalogue text. Pure: reads the persona files and the register only."""
    tasks = {e["id"]: e for e in task_register.load()}
    everyone = personas.load_all()
    out = ["# Persona catalogue", "",
           "Generated by `python docs/generate_persona_catalogue.py` from `src/cartogen_ai/core/personas/*.json` and the task register. Do not edit by hand: "
           "`tests/test_persona_catalogue.py` fails when this file is out of date.", "",
           "A persona is a lens, not a gate: it changes which tools are suggested first and how the assistant words its guidance. It never hides or blocks a tool, and it carries no licensing or tier logic. "
           "**Built** means a live run saw the capability working (`docs/LIVE_RESULTS.json`); **Available** means the tool exists and an automatic test covers it, which is weaker; "
           "**Not built** names the release of `docs/plans/PLAN-023-programme-1-18-2-to-1-30.md` that will deliver it.", "",
           "| # | Persona | Built | Available | Not built | Out of scope | Declined | Tasks |", "|---|---|---|---|---|---|---|---|"]
    for pid, p in everyone.items():
        counts = {state: sum(1 for r in p["readiness"] if r["state"] == state) for state, _ in HEADINGS}
        out.append(f"| {p['number']} | {p['label']} | {counts['built']} | {counts['CI-checked']} | {counts['not built']} | {counts['out of scope']} | {counts['declined']} | {len(p['task_ids'])} |")
    for pid, p in everyone.items():
        out += ["", f"## {p['number']}. {p['label']}", "", f"`{pid}`" + (f" (also called: {', '.join(p['aliases'])})" if p["aliases"] else ""), "", p["summary"], ""]
        if p["tool_priority"]:
            out += ["**Tools suggested first:** " + ", ".join(f"`{t}`" for t in p["tool_priority"]), ""]
        if p["workflows"]:
            out += ["**Workflows:**", ""]
            out += [f"- {w['title']}: " + " -> ".join(f"`{t}`" for t in w.get("tools", [])) for w in p["workflows"]]
            out.append("")
        if p["task_ids"]:
            out += ["**Tasks in the register:**", ""]
            out += [f"- {t} {tasks[t]['text']}" for t in p["task_ids"] if t in tasks]
            out.append("")
        for state, heading in HEADINGS:
            lines = [_line(r) for r in p["readiness"] if r["state"] == state]
            if lines:
                out += [f"**{heading}:**", ""] + [f"- {line}" for line in lines] + [""]
        extra = [("Data sources", p["data_sources"]), ("Style profile", [p["style_profile"]] if p["style_profile"] else []), ("Layout templates", p["layout_templates"])]
        for title, values in extra:
            if values:
                out.append(f"**{title}:** " + ", ".join(f"`{v}`" for v in values))
                out.append("")
        if p["guardrails"]:
            out += ["**The assistant will:**", ""] + [f"- {g}" for g in p["guardrails"]] + [""]
    return "\n".join(out).rstrip("\n") + "\n"


def main():
    text = render()
    if "--check" in sys.argv:
        current = open(PATH, encoding="utf-8").read() if os.path.exists(PATH) else ""
        if current != text:
            print("docs/PERSONA_CATALOGUE.md is stale: run python docs/generate_persona_catalogue.py")
            return 1
        print("docs/PERSONA_CATALOGUE.md is up to date")
        return 0
    with open(PATH, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(text)
    print("wrote", PATH)
    return 0


if __name__ == "__main__":
    sys.exit(main())
